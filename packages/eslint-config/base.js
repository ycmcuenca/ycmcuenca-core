// @ycmcuenca/eslint-config/base — the shared flat config every workspace
// member lints with: JavaScript, TypeScript, Svelte, JSON, YAML and Markdown.
// See design D3 and D5 in
// openspec/changes/archive/2026-10-17-bootstrap-monorepo/design.md.
import js from "@eslint/js";
import json from "@eslint/json";
import markdown from "@eslint/markdown";
import yml from "eslint-plugin-yml";
import { defineConfig, globalIgnores } from "eslint/config";
import tseslint from "typescript-eslint";
import prettier from "eslint-config-prettier";

// JavaScript and TypeScript rules apply to these files only. A config block
// without a `files` key also reaches JSON, YAML and Markdown files, whose
// languages cannot run JavaScript rules.
const scriptFiles = ["**/*.{js,mjs,cjs,jsx,ts,mts,cts,tsx}", "**/*.svelte"];

// Files the YAML plugin's rules apply to. Some of its config blocks come
// without a scope, which would run YAML rules (and its core-rule adjustments)
// on every other file; those blocks are restricted here.
const yamlFiles = ["**/*.yaml", "**/*.yml"];

export default defineConfig(
  // Generated output, caches and test reports are never linted.
  globalIgnores([
    "**/node_modules/**",
    "**/.svelte-kit/**",
    "**/build/**",
    "**/dist/**",
    "**/.wrangler/**",
    "**/.turbo/**",
    "**/coverage/**",
    "**/playwright-report/**",
    "**/test-results/**",
    // Written by `wrangler types`; regenerated, not hand-edited.
    "**/worker-configuration.d.ts",
    // Generated by Bun; not hand-edited.
    "bun.lock",
    // Generated by the OpenSpec CLI, and archive records that are historical
    // by definition. Matches .prettierignore.
    ".claude/**",
    ".opencode/**",
    "openspec/changes/archive/**",
  ]),
  // ESLint's own recommended rules for plain JavaScript, restricted to script
  // files so they never reach the other languages below.
  { ...js.configs.recommended, files: scriptFiles },
  // TypeScript rules for scripts and Svelte files, where `<script lang="ts">`
  // blocks are parsed with typescript-eslint (see svelte.js). The
  // non-type-checked variants on purpose: rules that need full type
  // information would slow lint down and mostly repeat what `bun run check`
  // (svelte-check / tsc) already verifies. Blocks that declare their own
  // scope (the core-rule overrides typescript-eslint applies to .ts files)
  // keep it; the rest are restricted to script files.
  ...tseslint.configs.recommended.map((config) =>
    config.files ? config : { ...config, files: scriptFiles },
  ),
  // package.json must stay strict JSON: npm and Bun parse it as such.
  {
    files: ["**/package.json"],
    plugins: { json },
    language: "json/json",
    extends: ["json/recommended"],
  },
  // Every other JSON file is JSONC, the dialect the tools that read them
  // accept: comments and trailing commas are normal in tsconfig.json,
  // turbo.jsonc, wrangler.jsonc and .vscode/*.json.
  {
    files: ["**/*.json", "**/*.jsonc"],
    ignores: ["**/package.json"],
    plugins: { json },
    language: "json/jsonc",
    languageOptions: { allowTrailingCommas: true },
    extends: ["json/recommended"],
  },
  // YAML (lefthook.yml, openspec/config.yaml, ...). Blocks that declare their
  // own scope keep it; the rest are restricted to YAML files. The plugin's
  // prettier config turns off the stylistic rules, since Prettier owns
  // formatting.
  ...yml.configs.recommended.map((config) =>
    config.files ? config : { ...config, files: yamlFiles },
  ),
  ...yml.configs.prettier.map((config) =>
    config.files ? config : { ...config, files: yamlFiles },
  ),
  // Markdown (README.md, ...), GitHub-flavored.
  {
    files: ["**/*.md"],
    plugins: { markdown },
    language: "markdown/gfm",
    extends: ["markdown/recommended"],
  },
  // Must stay last: it switches off ESLint rules that would fight Prettier,
  // which owns formatting in this workspace.
  prettier,
);
